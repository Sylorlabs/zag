#!/usr/bin/env bash
# Render the frozen ZagScript 1.0 capability contract from its TSV authority.
set -euo pipefail
cd "$(dirname "$0")/.."
matrix=tests/zagscript_1_0_capabilities.tsv

printf '%s\n\n' '# ZagScript 1.0 capability matrix'
printf '%s\n\n' 'Generated by `bash tests/generate_zagscript_1_0_matrix.sh`; do not edit manually.'
printf '%s\n\n' 'Linux x86-64 is the first authority. A 1.0 release requires every row to be `supported` by executable evidence.'
supported=$(awk -F '\t' '$3 == "supported" { n++ } END { print n+0 }' "$matrix")
partial=$(awk -F '\t' '$3 == "partial" { n++ } END { print n+0 }' "$matrix")
unavailable=$(awk -F '\t' '$3 == "unavailable" { n++ } END { print n+0 }' "$matrix")
actionable_supported=$(awk -F '\t' '$1 != "release" && $3 == "supported" { n++ } END { print n+0 }' "$matrix")
actionable_partial=$(awk -F '\t' '$1 != "release" && $3 == "partial" { n++ } END { print n+0 }' "$matrix")
actionable_unavailable=$(awk -F '\t' '$1 != "release" && $3 == "unavailable" { n++ } END { print n+0 }' "$matrix")
actionable_total=$((actionable_supported + actionable_partial + actionable_unavailable))
actionable_ready=0
if (( actionable_total > 0 )); then
actionable_ready=$(awk -v supported="$actionable_supported" -v total="$actionable_total" \
        'BEGIN { if (total == 0) { print "0.00" } else { printf "%.2f", (supported / total) * 100 } }')
fi
release_ready=0
if [[ "$actionable_partial" == "0" && "$actionable_unavailable" == "0" ]]; then
    release_ready=1
fi
printf '%s\n\n' '| Status | Rows |'
printf '%s\n' '|---|---:|'
printf '| supported | %s |\n' "$supported"
printf '| partial | %s |\n' "$partial"
printf '| unavailable | %s |\n\n' "$unavailable"
printf '%s\n\n' '| Actionable Status | Rows |'
printf '%s\n' '|---|---:|'
printf '| supported | %s |\n' "$actionable_supported"
printf '| partial | %s |\n' "$actionable_partial"
printf '| unavailable | %s |\n' "$actionable_unavailable"
printf '| actionable completion %s | %s |\n\n' "%" "$actionable_ready"
printf '| release ready | %s |\n\n' "$release_ready"
printf '%s\n' '| Area | Capability | Status | Evidence or blocker |'
printf '%s\n' '|---|---|---|---|'
tail -n +2 "$matrix" | while IFS=$'\t' read -r area capability status evidence; do
    printf '| %s | %s | `%s` | %s |\n' "$area" "$capability" "$status" "$evidence"
done
